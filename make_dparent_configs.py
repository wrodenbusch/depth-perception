#!/usr/bin/env python
"""Write config/{py,webc,chat,sheet}_dparent.py from each setting's 2-level reference config.

    .venv/bin/python make_dparent_configs.py

Generated rather than hand-copied so the four arms differ from their references in the pack,
the output directory and the plane comment ONLY. Python, Web-S and chat mirror their depth + rank
(``*_drank``) configs, which already rotate two numbers on 2 planes each with 44 idle; spreadsheets
have no depth + rank arm, so they mirror ``sheet_grid`` with its 3 levels cut to 2.
"""
from __future__ import annotations
from topos_paths import PACKS, RUNS  # noqa: E402

import re

HEADER = """from topos_paths import PACKS, RUNS  # noqa: E402
# TOPOS -- {setting}: sequence + DEPTH + PARENT TAG (sibling-group tag), 4 planes.
#
# THE IDEA (author, 2026-10-05): "depth plus parent ... all the children of 20 get marked as 20.
# Essentially tagging them all as a sibling group." Each token carries [depth, parent_tag]: the
# parent tag numbers the node's parent by first appearance, counted among parents at the same
# depth (depth_parent_pack.py --per-depth), so every child of one parent shares it and
# (depth, tag) identifies the sibling group across the whole document -- unlike sibling rank
# (the drank arm), which restarts under every parent.
#
# Generated by make_dparent_configs.py from config/{src}.py: identical except the pack and the
# output directory. rope_both with 2 levels rotates level 0 by depth and level 1 by the parent tag
# with the full path's ladder and presence handling; the other 44 planes are idle. Data:
# {pack}, every array but node_path a symlink, so the token stream is byte-identical to the base.
"""

ARMS = [
    ("py_drank", "py_dparent", "PYTHON AST", "{PACKS}/py_ast_423k_dparent",
     "{RUNS}/py/dparent_s0"),
    ("webc_drank", "webc_dparent", "WEB-S", "{PACKS}/web_whole_b2048_dparent",
     "{RUNS}/webc/dparent_s0"),
    ("chat_drank", "chat_dparent", "CHAT (WildChat)", "{PACKS}/chat_wildchat_b2048_dparent",
     "{RUNS}/chat/dparent_s0"),
    ("sheet_grid", "sheet_dparent", "SPREADSHEETS", "{PACKS}/sheet_values_v2_dparent",
     "{RUNS}/sheets/dparent_v2_s0"),
]

SUBS = [
    (r"^out_dir = .*$", "out_dir = f'{out}'"),
    (r"^pack = .*$", "pack = f'{pack}'"),
    (r"^rope_seq_planes, rope_levels, rope_planes_per_level = .*$",
     "rope_seq_planes, rope_levels, rope_planes_per_level = 16, 2, 2   "
     "# 16 seq + [depth, parent tag] x 2 + 44 idle = 64"),
    (r"^rope_token_planes = .*$",
     "rope_token_planes = 44                   # IDLE under rope_both; fills the allocation"),
]


def main() -> None:
    for src, dst, setting, pack, out in ARMS:
        body = open(f"config/{src}.py").read()
        body = body[body.index("out_dir ="):] if "\nout_dir =" in body or body.startswith("out_dir =") else body
        lines = body.splitlines()
        start = next(i for i, l in enumerate(lines) if l.startswith("out_dir ="))
        text = "\n".join(lines[start:]) + "\n"
        for pat, rep in SUBS:
            text, n = re.subn(pat, rep.format(out=out, pack=pack), text, count=1, flags=re.M)
            if not n:
                raise SystemExit(f"{src}: pattern {pat!r} not found")
        if "pos_mode = 'rope_both'" not in text:
            raise SystemExit(f"{src}: expected rope_both")
        with open(f"config/{dst}.py", "w") as f:
            f.write(HEADER.format(setting=setting, src=src, pack=pack) + text)
        print(f"wrote config/{dst}.py")


if __name__ == "__main__":
    main()
