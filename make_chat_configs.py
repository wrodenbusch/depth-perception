#!/usr/bin/env python
"""Write config/chat_<arm>.py for every chat arm, and the pending jobs file. Run once.

    .venv/bin/python make_chat_configs.py

Generated rather than hand-copied so the seven arms cannot drift apart: every setting except the
position mode, the pack and the plane allocation is identical, and that identity is the comparison.
"""
from __future__ import annotations
from topos_paths import PACKS, RUNS  # noqa: E402

import json

# Symbolic: generated configs resolve it through topos_paths at run time, not at generation.
P = "{PACKS}/chat_wildchat_b2048"
ARMS = {
    "seq": ("rope_seq", P, (16, 22, 2), 4, 0, "sequence only (16 planes; the baseline)."),
    "grid": ("rope_all", P + "_grid", (16, 22, 2), 4, 0,
             "THE USER'S QUESTION: sequence + the chat grid -- exchange (level 0, 2 planes), speaker "
             "(level 1, 2 planes; 0 = user, 1 = assistant) and the token's index within its message "
             "(the 4 token-leaf planes). Levels 2..21 are ABSENT in this pack: zero rotation."),
    "grid_depth": ("rope_all", P + "_griddepth", (16, 22, 2), 4, 0,
                   "sequence + the chat grid + Markdown depth below the speaker (level 2, 2 planes)."),
    "depth": ("rope_depth", P, (16, 22, 2), 0, 2,
              "sequence + depth (2 planes) in the exchange -> speaker -> Markdown tree."),
    "drank": ("rope_both", P + "_drank", (16, 2, 2), 44, 0,
              "sequence + depth + the node's own sibling rank (2 numbers x 2 planes; 44 idle)."),
    "both": ("rope_both", P, (16, 22, 2), 4, 0,
             "sequence + the full tree path (44 planes; token planes idle)."),
    "rel": ("rope_rel", P, (16, 22, 2), 0, 2, "sequence + full tree path + depth (62 planes)."),
}
#: grid and seq first -- the author's question -- then the Markdown-tree arms; seeds interleaved.
ORDER = ["seq", "grid", "grid_depth", "depth", "drank", "both", "rel"]
SEEDS = 10


def config_text(arm: str) -> str:
    mode, pack, (sq, lv, ppl), tok, rel, why = ARMS[arm]
    tok_c = ("the within-message index (rope_all rotates the token-leaf planes)" if mode == "rope_all"
             else "IDLE under this mode; fills the allocation" if mode in ("rope_seq", "rope_both")
             else "refused under this mode")
    derived = "" if pack == P else (
        "; derived by " + ("chat_grid_pack.py" if "grid" in pack else "depth_rank_pack.py")
        + ", every array but the sidecar symlinked, so the token stream is byte-identical to chat_seq")
    return f'''from topos_paths import PACKS, RUNS  # noqa: E402
# TOPOS -- CHAT (WildChat-1M, English, non-toxic; whole conversations <= 2,048 tokens, never cropped).
#
# THIS ARM: {why}
#
# Data: {pack.split('/')[-1]} -- built by build_chat_pack.py (tree: exchange -> speaker -> Markdown
# blocks; every message opens with its role line "User:" / "Assistant:"){derived}.
# Geometry, batching and LR mirror the Web-S configs (config/webc_*.py). LR 1.2e-3 is Web-S's
# smoked rate, NOT re-smoked on chat; a 600-step 3-rate smoke on chat_seq would confirm it.
# max_iters: ~300M tokens at 716 tokens/record x 32 records/step = 22.9k tokens/step -> 13,100
# steps. The train split holds 208.7M tokens, so this is ~1.44 passes (some repetition).
# Generated by make_chat_configs.py -- edit there, not here.
out_dir = f'{{RUNS}}/chat/{arm}_s0'
pack = f'{pack}'
pos_mode = '{mode}'
seed = 0
block_size = 2048
vocab_size = 50304
n_layer, n_head, n_embd = 6, 2, 256      # head dim 128, so 64 rotary planes; ~4.7M non-embedding
rope_seq_planes, rope_levels, rope_planes_per_level = {sq}, {lv}, {ppl}
rope_token_planes = {tok}                    # {tok_c}
rope_rel_planes = {rel}
rope_decay = False
bias = False
dropout = 0.0
bucket_batching = True
records_per_step = 32
token_budget = 8192
batch_size = 2                           # unused under bucket_batching, kept for the record
gradient_accumulation_steps = 16
learning_rate = 1.2e-3
min_lr = 1.2e-4
max_iters = 13100
lr_decay_iters = 13100
warmup_iters = 262                       # 2%
weight_decay = 0.1
grad_clip = 1.0
beta1, beta2 = 0.9, 0.95
eval_interval = 655                      # 5% -> 20 milestones
eval_records = 1024
log_interval = 20
compile = False                          # as Web-S: bucket batching makes up to 128 shapes
'''


def main() -> None:
    for arm in ARMS:
        with open(f"config/chat_{arm}.py", "w") as f:
            f.write(config_text(arm))
    jobs = []
    for s in range(SEEDS):
        for arm in ORDER:
            out = f"{RUNS}/chat/{arm}_s{s}"
            jobs.append(dict(name=f"chat_{arm}_s{s}", out=out, log=f"{out}/stdout.log",
                             cmd=f".venv/bin/python train.py config/chat_{arm}.py --seed={s} --out_dir={out}"))
    path = f"{RUNS}/controls/chat_jobs.PENDING.json"
    with open(path, "w") as f:
        json.dump(jobs, f, indent=1)
    print(f"wrote {len(ARMS)} configs and {len(jobs)} jobs -> {path}")


if __name__ == "__main__":
    main()
